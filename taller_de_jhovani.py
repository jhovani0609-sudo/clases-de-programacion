import pandas as pd
import matplotlib.pyplot as plt
import os

# === CONFIGURA TU ARCHIVO AQUÍ ===
# Si es.csv -> FILE = "tu_archivo.csv"
# Si es.xlsx -> FILE = "tu_archivo.xlsx"
FILE = "/content/Civil Engineering Global Project Dataset.csv" # <-- CAMBIA ESTO POR EL NOMBRE DE TU ARCHIVO

# Lectura optimizada para archivos pesados
def load_data(file):
    ext = os.path.splitext(file)[1].lower()
    if ext == '.csv':
        # Lee en chunks si es muy pesado
        try:
            df = pd.read_csv(file)
        except MemoryError:
            print("Archivo muy pesado, leyendo por partes...")
            chunks = pd.read_csv(file, chunksize=100000)
            df = pd.concat(chunks)
    else:
        df = pd.read_excel(file)
    print(f"Filas: {len(df)}, Columnas: {list(df.columns)}")
    return df

df = load_data(FILE)

# --- 1. Costo promedio por tramo salarial ---
print("\n1. COSTO PROMEDIO POR SALARY BRACKET")
print(df.groupby('Salary Bracket')['Project Cost'].mean())

# --- 2. Correlación edad-experiencia ---
print("\n2. CORRELACIÓN EDAD-EXPERIENCIA")
corr_edad_exp = df['age'].corr(df['Years of Experience'])
print(f"Pearson: {corr_edad_exp:.3f}")

# --- 3. Riesgo de infracción por PCAB ---
print("\n3. RIESGO POR PCAB SCORE (describe)")
print(df.groupby('Company PCAB Score')['Violation Risk Index'].describe())

# --- 4. Certificaciones vs Rendimiento ---
print("\n4. CERTIFICACIONES PROMEDIO POR IS_GOOD")
print(df.groupby('is_good')['Certificates'].mean())

# --- 5. Impacto financiero por PCAB ---
print("\n5. COSTO TOTAL ACUMULADO POR PCAB")
print(df.groupby('Company PCAB Score')['Project Cost'].sum().sort_values(ascending=False))

# --- 6. Horas extra y riesgo ---
print("\n6. CORRELACIÓN HORAS EXTRA - RIESGO")
print(df['Weekly Overtime Hours'].corr(df['Violation Risk Index']))

# --- 7. Proximidad por salario (media y desv) ---
print("\n7. PROXIMIDAD POR SALARY BRACKET")
print(df.groupby('Salary Bracket')['Project Proximity'].agg(['mean','std']))

# --- 8. Distribución éxito ---
print("\n8. DISTRIBUCIÓN IS_GOOD")
print(df['is_good'].value_counts(normalize=True)*100)

# --- 9. Horas extra según experiencia ---
print("\n9. HORAS EXTRA PROMEDIO POR EXPERIENCIA")
print(df.groupby('Years of Experience')['Weekly Overtime Hours'].mean())

# --- 10. Estadísticas costos por PCAB ---
print("\n10. MAX, MIN, MEDIANA POR PCAB")
print(df.groupby('Company PCAB Score')['Project Cost'].agg(['max','min','median']))

# === GRÁFICOS RÁPIDOS ===
plt.figure()
df.groupby('Salary Bracket')['Project Cost'].mean().plot(kind='bar')
plt.title('1. Costo promedio por Salary Bracket')
plt.savefig('1_costo_salario.png')

plt.figure()
plt.scatter(df['age'], df['Years of Experience'], alpha=0.3)
plt.title(f'2. Edad vs Experiencia (r={corr_edad_exp:.2f})')
plt.savefig('2_edad_exp.png')

print("\n¡Listo! Gráficos guardados como PNG")